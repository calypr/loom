package main

import (
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
)

func generateValidate(schema *Schema, path string) error {
	var sb strings.Builder
	sb.WriteString("// Code generated by cmd/generate/main.go. DO NOT EDIT.\n")
	sb.WriteString("package fhir\n\n")
	var keys []string
	for key := range schema.Defs {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	patterns := make(map[string]struct{})
	usesStringLengths := false
	for _, definition := range schema.Defs {
		for _, property := range definition.Properties {
			usesStringLengths = usesStringLengths || property.MinLength != nil || property.MaxLength != nil
			for _, value := range []*Property{property, property.Items} {
				if hasStringPattern(value) && fastStringPattern(value.Pattern, "") == "" {
					patterns[value.Pattern] = struct{}{}
				}
			}
		}
	}
	patternKeys := make([]string, 0, len(patterns))
	for pattern := range patterns {
		patternKeys = append(patternKeys, pattern)
	}
	sort.Strings(patternKeys)
	regexNames := make(map[string]string, len(patternKeys))

	sb.WriteString("import (\n\t\"fmt\"\n")
	if len(patternKeys) > 0 {
		sb.WriteString("\t\"regexp\"\n")
	}
	if usesStringLengths {
		sb.WriteString("\t\"unicode/utf8\"\n")
	}
	sb.WriteString(")\n\n")
	sb.WriteString("type MissingRequiredFieldError struct { Field string }\n\n")
	sb.WriteString("func (e *MissingRequiredFieldError) Error() string { return fmt.Sprintf(\"required field '%s' is missing\", e.Field) }\n\n")
	for index, pattern := range patternKeys {
		name := fmt.Sprintf("validationPattern%d", index)
		regexNames[pattern] = name
		fmt.Fprintf(&sb, "var %s = regexp.MustCompile(%q)\n", name, pattern)
	}
	sb.WriteByte('\n')

	for _, k := range keys {
		def := schema.Defs[k]
		sb.WriteString(fmt.Sprintf("// Validate validates a %s struct against its schema constraints.\n", k))
		sb.WriteString(fmt.Sprintf("func (x *%s) Validate() error {\n", k))
		sb.WriteString("\tif x == nil {\n\t\treturn nil\n\t}\n")

		var propKeys []string
		for pk := range def.Properties {
			propKeys = append(propKeys, pk)
		}
		sort.Strings(propKeys)

		for _, pk := range propKeys {
			prop := def.Properties[pk]
			required := isRequired(def, pk)
			goName := "x." + toGoName(pk)

			if required {
				sb.WriteString(fmt.Sprintf("\tif %s == nil {\n", goName))
				sb.WriteString(fmt.Sprintf("\t\treturn &MissingRequiredFieldError{Field: %q}\n", pk))
				sb.WriteString("\t}\n")
			}

			goType := getGoType(prop, true)
			isPointer := strings.HasPrefix(goType, "*")
			isSlice := strings.HasPrefix(goType, "[]")
			isCustomComments := goType == "FHIRComments"

			if isCustomComments {

				continue
			}

			indent := "\t"
			if isPointer {
				sb.WriteString(fmt.Sprintf("\tif %s != nil {\n", goName))
				indent = "\t\t"
			} else if isSlice {
				sb.WriteString(fmt.Sprintf("\tif %s != nil {\n", goName))
				indent = "\t\t"
			}

			valExpr := goName
			if isPointer {
				valExpr = "*" + goName
			}

			if prop.Const != nil {
				constStr, ok := prop.Const.(string)
				if ok {
					sb.WriteString(fmt.Sprintf("%sif %s != %s {\n", indent, valExpr, strconv.Quote(constStr)))
					sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' must be exactly '%s'\")\n", indent, pk, constStr))
					sb.WriteString(fmt.Sprintf("%s}\n", indent))
				}
			}
			if len(prop.EnumValues) > 0 {
				var conditions []string
				for _, enumValue := range prop.EnumValues {
					conditions = append(conditions, fmt.Sprintf("%s == %s", valExpr, strconv.Quote(enumValue)))
				}
				sb.WriteString(fmt.Sprintf("%sif !(%s) {\n", indent, strings.Join(conditions, " || ")))
				sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' has an unsupported value\")\n", indent, pk))
				sb.WriteString(fmt.Sprintf("%s}\n", indent))
			}

			if hasStringPattern(prop) {
				condition := invalidStringPattern(prop.Pattern, valExpr, regexNames)
				fmt.Fprintf(&sb, "%sif %s {\n%s\treturn fmt.Errorf(\"field '%s' does not match its schema pattern\")\n%s}\n", indent, condition, indent, pk, indent)
			}

			if prop.MinLength != nil {
				sb.WriteString(fmt.Sprintf("%sif utf8.RuneCountInString(%s) < %d {\n", indent, valExpr, *prop.MinLength))
				sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' is too short (min %d characters)\")\n", indent, pk, *prop.MinLength))
				sb.WriteString(fmt.Sprintf("%s}\n", indent))
			}

			if prop.MaxLength != nil {
				sb.WriteString(fmt.Sprintf("%sif utf8.RuneCountInString(%s) > %d {\n", indent, valExpr, *prop.MaxLength))
				sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' is too long (max %d characters)\")\n", indent, pk, *prop.MaxLength))
				sb.WriteString(fmt.Sprintf("%s}\n", indent))
			}

			if prop.Minimum != nil {
				sb.WriteString(fmt.Sprintf("%sif %s < %f {\n", indent, valExpr, *prop.Minimum))
				sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' is below minimum %f\")\n", indent, pk, *prop.Minimum))
				sb.WriteString(fmt.Sprintf("%s}\n", indent))
			}

			if prop.ExclusiveMinimum != nil {
				sb.WriteString(fmt.Sprintf("%sif %s <= %f {\n", indent, valExpr, *prop.ExclusiveMinimum))
				sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' is below exclusive minimum %f\")\n", indent, pk, *prop.ExclusiveMinimum))
				sb.WriteString(fmt.Sprintf("%s}\n", indent))
			}

			if propertyHasNestedValidation(prop) {
				sb.WriteString(fmt.Sprintf("%sif err := %s.Validate(); err != nil {\n", indent, goName))
				sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s' is invalid: %%w\", err)\n", indent, pk))
				sb.WriteString(fmt.Sprintf("%s}\n", indent))
			}

			if isSlice && prop.Items != nil {
				hasItemValidation := hasStringPattern(prop.Items) || len(prop.Items.EnumValues) > 0 || propertyHasNestedValidation(prop.Items)
				if hasItemValidation {
					itemName := "item"
					sb.WriteString(fmt.Sprintf("%sfor i, %s := range %s {\n", indent, itemName, valExpr))
					loopIndent := indent + "\t"

					itemValExpr := itemName
					itemIsPointer := strings.HasPrefix(getGoType(prop.Items, false), "*")
					if itemIsPointer {
						sb.WriteString(fmt.Sprintf("%sif %s != nil {\n", loopIndent, itemName))
						loopIndent += "\t"
						itemValExpr = "*" + itemName
					}

					if hasStringPattern(prop.Items) {
						condition := invalidStringPattern(prop.Items.Pattern, itemValExpr, regexNames)
						fmt.Fprintf(&sb, "%sif %s {\n%s\treturn fmt.Errorf(\"field '%s[%%d]' does not match its schema pattern\", i)\n%s}\n", loopIndent, condition, loopIndent, pk, loopIndent)
					}

					if propertyHasNestedValidation(prop.Items) {
						sb.WriteString(fmt.Sprintf("%sif err := %s.Validate(); err != nil {\n", loopIndent, itemName))
						sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s[%%d]' is invalid: %%w\", i, err)\n", loopIndent, pk))
						sb.WriteString(fmt.Sprintf("%s}\n", loopIndent))
					}
					if len(prop.Items.EnumValues) > 0 {
						var conditions []string
						for _, enumValue := range prop.Items.EnumValues {
							conditions = append(conditions, fmt.Sprintf("%s == %s", itemValExpr, strconv.Quote(enumValue)))
						}
						sb.WriteString(fmt.Sprintf("%sif !(%s) {\n", loopIndent, strings.Join(conditions, " || ")))
						sb.WriteString(fmt.Sprintf("%s\treturn fmt.Errorf(\"field '%s[%%d]' has an unsupported value\", i)\n", loopIndent, pk))
						sb.WriteString(fmt.Sprintf("%s}\n", loopIndent))
					}

					if itemIsPointer {
						sb.WriteString(fmt.Sprintf("%s}\n", indent+"\t"))
					}
					sb.WriteString(fmt.Sprintf("%s}\n", indent))
				}
			}

			if isPointer || isSlice {
				sb.WriteString("\t}\n")
			}
		}
		sb.WriteString("\treturn nil\n")
		sb.WriteString("}\n\n")
	}

	return os.WriteFile(path, []byte(sb.String()), 0644)
}

func hasStringPattern(property *Property) bool {
	return property != nil && property.Type == "string" && property.Pattern != ""
}

func propertyHasNestedValidation(property *Property) bool {
	ref := refName(property.Ref)
	return ref != "" && ref != "ResourceList" && ref != "links"
}
