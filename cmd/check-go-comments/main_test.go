package main

import (
	"go/token"
	"testing"
)

func TestCheckFile(t *testing.T) {
	for _, test := range []struct {
		name   string
		source string
		want   int
	}{
		{"ordinary", "package p\n// explain the next line\nconst a = 1 // trailing text\n", 2},
		{"block", "package p\nconst a = /* a value */ 1\n", 1},
		{"directives", "//go:build ci\n\npackage p\n//go:generate go run gen.go\n", 0},
		{"unknown directive", "package p\n//go:comment this is ordinary prose\n", 1},
		{"mixed", "package p\n// go run the generator\n//go:generate go run gen.go\n", 1},
		{"generated", "// Code generated by example. DO NOT EDIT.\n\npackage p\n// Generated documentation\n", 0},
		{"fake generated", "package p\n// Code generated by example. DO NOT EDIT.\n", 1},
		{"essential", "package p\n// Essential: callers depend on this wire format.\n// Older clients omit the field.\nconst a = 1\n", 0},
		{"empty reason", "package p\n// Essential: \nconst a = 1\n", 1},
		{"cgo preamble", "package p\n/* #include <stdlib.h> */\nimport \"C\"\n// ordinary\n", 1},
		{"example output", "package p\nfunc Example() {\n// Output:\n// hello\n}\n", 0},
		{"output elsewhere", "package p\nfunc Print() {\n// Output: hello\n}\n", 1},
		{"literal", "package p\nconst a = \"// comment-like content\"\n", 0},
	} {
		t.Run(test.name, func(t *testing.T) {
			violations, err := checkFile(token.NewFileSet(), "example_test.go", test.source)
			if err != nil {
				t.Fatal(err)
			}
			if len(violations) != test.want {
				t.Fatalf("got violations %v, want %d", violations, test.want)
			}
		})
	}
}
