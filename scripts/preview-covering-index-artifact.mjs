#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';

const packagePattern = './cmd/preview-covering-index-artifact';
const moduleRoot = realpathSync(resolve(dirname(fileURLToPath(import.meta.url)), '..'));
const args = process.argv.slice(2);
if (args.some((argument) => argument === '-source-manifest' || argument.startsWith('-source-manifest='))) {
  throw new Error('the source manifest is generated by this wrapper and cannot be overridden');
}

const goListText = execFileSync('go', ['list', '-deps', '-json', packagePattern], {
  cwd: moduleRoot,
  encoding: 'utf8',
  env: process.env,
});
const packagesFromList = parseJSONStream(goListText);
const packages = new Set();
const files = new Map();
let module = '';
for (const item of packagesFromList) {
  if (!item.Dir || !item.ImportPath) continue;
  const packageDirectory = realpathSync(item.Dir);
  if (!isWithin(moduleRoot, packageDirectory)) continue;
  packages.add(item.ImportPath);
  if (item.Module?.Main) module = item.Module.Path;
  const fileNames = [
    item.GoFiles, item.CgoFiles, item.CFiles, item.CXXFiles, item.HFiles,
    item.FFiles, item.SFiles, item.SwigFiles, item.SwigCXXFiles,
    item.SysoFiles, item.EmbedFiles,
  ].flatMap((value) => value ?? []);
  for (const fileName of fileNames) {
    const fullPath = realpathSync(join(packageDirectory, fileName));
    if (!isWithin(moduleRoot, fullPath)) throw new Error(`production source escapes module root: ${fileName}`);
    files.set(relative(moduleRoot, fullPath).split(sep).join('/'), fullPath);
  }
}
if (!module || packages.size === 0) throw new Error('go list did not return the current Loom production module closure');
files.set('scripts/preview-covering-index-artifact.mjs', realpathSync(fileURLToPath(import.meta.url)));
for (const manifestFile of ['go.mod', 'go.sum', 'go.work', 'go.work.sum', 'vendor/modules.txt']) {
  const fullPath = join(moduleRoot, manifestFile);
  if (existsSync(fullPath)) files.set(manifestFile, realpathSync(fullPath));
}
const sortedPackages = [...packages].sort(compareUTF8);
const sourceFiles = [...files.entries()]
  .map(([path, fullPath]) => ({ path, sha256: sha256(readFileSync(fullPath)) }))
  .sort((left, right) => compareUTF8(left.path, right.path));
const canonical = `module:${module}\npackage:${packagePattern}\n` +
  sortedPackages.map((value) => `package:${value}\n`).join('') +
  sourceFiles.map(({ path, sha256: digest }) => `file:${path}:${digest}\n`).join('');
const sourceManifest = {
  algorithm: 'sha256',
  module,
  package: packagePattern,
  packages: sortedPackages,
  files: sourceFiles,
  fileCount: sourceFiles.length,
  sha256: sha256(canonical),
};
const temporaryDirectory = mkdtempSync(join(tmpdir(), 'loom-preview-index-source-'));
const manifestPath = join(temporaryDirectory, 'source-manifest.json');
try {
  writeFileSync(manifestPath, JSON.stringify(sourceManifest), { mode: 0o600 });
  process.stderr.write(`captured pre-build source closure sha256: ${sourceManifest.sha256} (${sourceManifest.fileCount} files)\n`);
  const result = spawnSync('go', ['run', packagePattern, '-source-manifest', manifestPath, ...args], {
    cwd: moduleRoot,
    stdio: 'inherit',
    env: process.env,
  });
  if (result.error) throw result.error;
  process.exitCode = result.status ?? 1;
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}

function parseJSONStream(value) {
  const objects = [];
  let depth = 0;
  let start = -1;
  let inString = false;
  let escaped = false;
  for (let index = 0; index < value.length; index++) {
    const character = value[index];
    if (start < 0) {
      if (character === '{') {
        start = index;
        depth = 1;
      }
      continue;
    }
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') inString = true;
    else if (character === '{') depth++;
    else if (character === '}' && --depth === 0) {
      objects.push(JSON.parse(value.slice(start, index + 1)));
      start = -1;
    }
  }
  if (start >= 0 || objects.length === 0) throw new Error('go list returned an incomplete JSON package stream');
  return objects;
}

function isWithin(root, target) {
  const path = relative(root, target);
  return path === '' || (path !== '..' && !path.startsWith(`..${sep}`));
}

function compareUTF8(left, right) {
  return Buffer.compare(Buffer.from(left), Buffer.from(right));
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}
