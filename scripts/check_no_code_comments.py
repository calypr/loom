GOVERNANCE_DIRECTIVE_INDEX = {
    os.path.join(REPO, k): v for k, v in GOVERNANCE_DIRECTIVES.items()
}

REVIEWED_SOURCE_LEDGERS = (
    "verification/builder-interactions/reviewed-sources.json",
    "verification/publication-bundle/reviewed-sources.json",
)


def ledger_bound_paths():
    """Paths byte-pinned by verification reviewed-source ledgers (md5/sha
    verified). Their comments are evidence payloads; never rewritten."""
    bound = {}
    for rel in REVIEWED_SOURCE_LEDGERS:
        full = os.path.join(REPO, rel)
        if not os.path.isfile(full):
            continue
        with open(full) as f:
            data = json.load(f)
        files = data.get("files")
        if isinstance(files, dict):
            for p in files:
                bound[os.path.normpath(os.path.join(REPO, p))] = rel
    return bound


"""Bytes here are runtime payload, not source: checksummed into the postgres
migration ledger (ErrMigrationChecksumMismatch) or consumed as testdata
fixtures. Stripping comments changes hashes = behavior change."""
MIGRATION_TREE = "internal/backends/postgres/internal/"
AB05_FIXTURE_TREE = ("internal/backends/postgres/internal/store/testdata/"
                     "ab05_pre_refactor/")


def is_checksum_payload(rel):
    return (rel.startswith(MIGRATION_TREE) and not rel.startswith(AB05_FIXTURE_TREE)
            and "/migrations/" in rel and rel.endswith(".sql"))


def is_fixture_payload(rel):
    return rel.startswith(AB05_FIXTURE_TREE) and rel.endswith(".sql")



def tracked_paths():
    p = subprocess.run(["git", "-C", REPO, "ls-tree", "-r", "--name-only", "HEAD"],
                       capture_output=True, text=True, check=True)
    return [l for l in p.stdout.splitlines() if l]


def read(rel):
    full = os.path.join(REPO, rel)
    if not os.path.isfile(full):
        return None
    with open(full, "rb") as f:
        raw = f.read()
    if b"\x00" in raw[:8192]:
        return None
    return raw.decode("utf-8", errors="replace")


def scan(paths, json_out=None):
    inventory = {"asset": [], "unsupported": [], "binary": [],
                 "checksum-payload": [], "fixture-payload": [],
                 "provenance-generated": [], "ledger-bound": [],
                 "unresolvable-ledger-key": []}
    ledger_bound = ledger_bound_paths()
    tracked = set(tracked_paths())
    for key in sorted(ledger_bound):
        rel = os.path.relpath(key, REPO)
        if rel not in tracked:
            inventory["unresolvable-ledger-key"].append(
                {"path": rel, "ledger": ledger_bound[key]})
    violations = []
    allowed = []
    ts_paths = [p for p in paths if b.classify(p) == "ts"]
    ts_results = {}
    if ts_paths:
        ts_results = b.detect_ts_family([os.path.join(REPO, p) for p in ts_paths], REPO)
    ts_batch = {}
    for p in ts_paths:
        ts_batch[p] = ts_results.get(os.path.join(REPO, p), [])
    for rel in paths:
        relkey = os.path.relpath(os.path.abspath(os.path.join(REPO, rel)), REPO)
        backend = b.classify(rel)
        if backend == "asset":
            inventory["asset"].append(rel)
            continue
        if backend == "UNSUPPORTED":
            inventory["unsupported"].append(rel)
            continue
        if is_checksum_payload(relkey):
            inventory["checksum-payload"].append(rel)
            continue
        if is_fixture_payload(relkey):
            inventory["fixture-payload"].append(rel)
            continue
        src = read(relkey)
        if src is None:
            inventory["binary"].append(rel)
            continue
        relabs = os.path.abspath(os.path.join(REPO, rel))
        provenance = {}
        if relabs in PROVENANCE_LEDGER:
            entry = PROVENANCE_LEDGER[relabs]
            if re.search(entry["banner"], src):
                provenance[relabs] = entry
                inventory["provenance-generated"].append(rel)
            else:
                violations.append({"path": rel, "backend": backend, "line": 0,
                                   "kind": "provenance", "text":
                                       "listed generator file missing expected banner: "
                                       + entry["banner"]})
        elif relabs in GQLGEN_RESOLVERS:
            if re.search(GQLGEN_RESOLVER_BANNER, src):
                provenance[relabs] = {"generator": "gqlgen", "regen": "make generate-graphql"}
                inventory["provenance-generated"].append(rel)
            else:
                violations.append({"path": rel, "backend": backend, "line": 0,
                                   "kind": "provenance", "text":
                                       "gqlgen resolver missing generated banner"})
        governance = {}
        if relabs in GOVERNANCE_DIRECTIVE_INDEX:
            governance[relabs] = GOVERNANCE_DIRECTIVE_INDEX[relabs]
        if relabs in ledger_bound:
            inventory["ledger-bound"].append(rel)
        if backend == "ts":
            comments = ts_batch[rel]
        else:
            backend_name, comments, error = b.detect_file(rel, src)
            if error:
                violations.append({"path": rel, "backend": backend, "line": 0,
                                   "kind": "parse", "text": error})
                continue
        lines = src.splitlines()
        for c in comments:
            line_text = lines[c["line"] - 1] if 0 < c["line"] <= len(lines) else ""
            category = b.allowlist_category(backend, c, line_text, relabs,
                                            provenance, governance)
            record = {"path": rel, "backend": backend, "line": c["line"],
                      "kind": c["kind"], "text": c["text"][:120]}
            if category:
                record["category"] = category
                allowed.append(record)
            else:
                violations.append(record)
    summary = {
        "filesScanned": len(paths),
        "violations": violations,
        "allowed": allowed,
        "inventory": inventory,
    }
    if json_out:
        with open(json_out, "w") as f:
            json.dump(summary, f, indent=1, sort_keys=True)
    return summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all-tracked", action="store_true")
    ap.add_argument("--json-out")
    ap.add_argument("paths", nargs="*")
    args = ap.parse_args()
    paths = tracked_paths() if args.all_tracked else args.paths
    if not paths:
        print("no paths selected", file=sys.stderr)
        return 2
    summary = scan(paths, args.json_out)
    for v in summary["violations"]:
        print(f"VIOLATION {v['path']}:{v['line']} [{v['backend']}/{v['kind']}] {v['text']!r}")
    for rel in summary["inventory"]["unsupported"]:
        print(f"UNSUPPORTED {rel}")
    for entry in summary["inventory"]["unresolvable-ledger-key"]:
        print(f"UNRESOLVABLE-LEDGER-KEY {entry['path']} ({entry['ledger']})")
    inv = summary["inventory"]
    print(f"scanned={summary['filesScanned']} violations={len(summary['violations'])} "
          f"allowed={len(summary['allowed'])} assets={len(inv['asset'])} "
          f"checksum-payload={len(inv['checksum-payload'])} "
          f"fixture-payload={len(inv['fixture-payload'])} "
          f"provenance-generated={len(inv['provenance-generated'])} "
          f"ledger-bound={len(inv['ledger-bound'])} "
          f"unresolvable-ledger-key={len(inv['unresolvable-ledger-key'])} "
          f"unsupported={len(inv['unsupported'])} binary={len(inv['binary'])}")
    return 1 if summary["violations"] or summary["inventory"]["unsupported"] else 0


if __name__ == "__main__":
    sys.exit(main())
