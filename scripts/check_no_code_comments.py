#!/usr/bin/env python3
"""Repository-wide handwritten-comment gate.

Drives scripts/lib/no_code_comments_backends.py over every tracked path,
re-enumerated from git (git ls-tree -r HEAD; git ls-files is rejected because
an empty index silently reports zero files). Fails on handwritten comments;
permits only enumerated language directives and provenance-ledger generator
output. Markdown and data assets are inventoried, never rewritten. Unsupported
formats are reported, never silently excluded.

Usage:
  check_no_code_comments.py --all-tracked [--json-out PATH]
  check_no_code_comments.py PATH [PATH ...] [--json-out PATH]
"""

