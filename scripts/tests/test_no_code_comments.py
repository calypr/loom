class Harness(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self._prov = dict(chk.PROVENANCE_LEDGER)
        self._resolvers = set(chk.GQLGEN_RESOLVERS)
        self.addCleanup(self._restore)
        self.addCleanup(self._tmp.cleanup)

    def _restore(self):
        chk.PROVENANCE_LEDGER.clear()
        chk.PROVENANCE_LEDGER.update(self._prov)
        chk.GQLGEN_RESOLVERS.clear()
        chk.GQLGEN_RESOLVERS.update(self._resolvers)

    def write(self, name, content):
        path = os.path.join(self._tmp.name, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(content)
        return path

    def scan(self, *paths):
        return chk.scan(list(paths))


class GoCommentDetection(Harness):
    def test_inline_block_doc_commented_code_and_todo_fail(self):
        p = self.write("a.go", "package a // trailing note\n\n"
                               "/* block note */\n"
                               "// Doc explains the function.\n"
                               "func Doc() {}\n\n"
                               "// TODO: fix later\n"
                               "func T() {}\n\n"
                               "func C() {\n\t// x := 1\n\t// y := x + 1\n}\n")
        s = self.scan(p)
        texts = [v["text"] for v in s["violations"]]
        self.assertEqual(len(texts), 6, texts)

    def test_go_directives_pass(self):
        p = self.write("d.go", "#!/usr/bin/env go-run\n"
                               "//go:build integration\n"
                               "//go:embed migrations/*.sql\n"
                               "//go:generate stringer -type=Level\n"
                               "package d\n")
        s = self.scan(p)
        self.assertEqual([], s["violations"])
        self.assertEqual(4, len(s["allowed"]))

    def test_string_and_raw_string_markers_are_not_comments(self):
        p = self.write("s.go", "package s\n"
                               'const url = "https://example.com//path#frag"\n'
                               'const raw = `/* not a comment */ // nor this`\n'
                               'const esc = "he said \\"//x\\" // trailing? no, in string"\n')
        s = self.scan(p)
        self.assertEqual([], s["violations"])


class GeneratedProvenance(Harness):
    def test_generated_path_name_alone_does_not_exempt(self):
        p = self.write("whatever.gen.go", "// Code generated by magic. DO NOT EDIT.\n"
                                          "package g\n\n// handwritten helper note\n"
                                          "func H() {}\n")
        s = self.scan(p)
        self.assertEqual(2, len(s["violations"]))

    def test_listed_generator_file_missing_banner_fails(self):
        p = self.write("model.go", "package fhir\n\n// handwritten note\nvar X = 1\n")
        chk.PROVENANCE_LEDGER.clear()
        chk.PROVENANCE_LEDGER[p] = {
            "generator": "cmd/generate", "regen": "make generate-fhir",
            "banner": r"Code generated by cmd/generate/main\.go\. DO NOT EDIT\."}
        s = self.scan(p)
        kinds = [v["kind"] for v in s["violations"]]
        self.assertIn("provenance", kinds)
        self.assertIn("handwritten note", " ".join(v["text"] for v in s["violations"]))

    def test_listed_generator_file_with_banner_passes(self):
        p = self.write("model.go", "// Code generated by cmd/generate/main.go. DO NOT EDIT.\n"
                                   "package fhir\n\n// generated schema table\nvar X = 1\n")
        chk.PROVENANCE_LEDGER.clear()
        chk.PROVENANCE_LEDGER[p] = {
            "generator": "cmd/generate", "regen": "make generate-fhir",
            "banner": r"Code generated by cmd/generate/main\.go\. DO NOT EDIT\."}
        s = self.scan(p)
        self.assertEqual([], s["violations"])
        self.assertTrue(s["allowed"])
        self.assertEqual({"generator-provenance"},
                         {a["category"] for a in s["allowed"]})

    def test_gqlgen_resolver_requires_version_banner(self):
        ok = self.write("ok.resolvers.go", "package resolver\n"
                                           "// Code generated by github.com/99designs/gqlgen version v0.17.94\n"
                                           "// City is the resolver for the city field.\nfunc City() {}\n")
        bad = self.write("bad.resolvers.go", "package resolver\n"
                                             "// City is the resolver for the city field.\nfunc City() {}\n")
        chk.GQLGEN_RESOLVERS.clear()
        chk.GQLGEN_RESOLVERS.update({ok, bad})
        self.assertEqual([], self.scan(ok)["violations"])
        kinds = {v["kind"] for v in self.scan(bad)["violations"]}
        self.assertIn("provenance", kinds)
        self.assertIn("line", kinds)

    def test_repo_generated_files_pass(self):
        s = self.scan(
            os.path.join(chk.REPO, "generated/fhir/model.go"),
            os.path.join(chk.REPO, "generated/loomapi/api.gen.go"),
            os.path.join(chk.REPO, "generated/graphql/graph/executor/schema.generated.go"),
            os.path.join(chk.REPO, "internal/api/graphql/graph/resolver/fhir_schema.resolvers.go"))
        self.assertEqual([], s["violations"])


class LedgerBound(Harness):
    def test_ledger_pinning_alone_does_not_exempt(self):
        path = self.write("pinned.go", "package p\n\n// handwritten note under a pin\nvar X = 1\n")
        original = chk.ledger_bound_paths
        chk.ledger_bound_paths = lambda: {path: "fixture-ledger"}
        self.addCleanup(setattr, chk, "ledger_bound_paths", original)
        s = self.scan(path)
        self.assertEqual(1, len(s["violations"]))
        self.assertIn("handwritten note", s["violations"][0]["text"])
        self.assertEqual([path], s["inventory"]["ledger-bound"])

