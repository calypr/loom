class InventoryAndCli(Harness):
    def test_parse_error_is_violation_not_skip(self):
        p = self.write("broken.json", '{"a": ')
        s = self.scan(p)
        self.assertEqual(["parse"], [v["kind"] for v in s["violations"]])

    def test_unsupported_is_reported_and_exit_code_nonzero(self):
        c = self.write("mystery.zzz", "content\n")
        s = self.scan(c)
        self.assertEqual([c], s["inventory"]["unsupported"])
        argv = sys.argv
        sys.argv = ["check_no_code_comments.py", c]
        try:
            self.assertEqual(1, chk.main())
        finally:
            sys.argv = argv

    def test_self_compliance_of_owned_files(self):
        files = [
            os.path.join(chk.REPO, "scripts/check_no_code_comments.py"),
            os.path.join(chk.REPO, "scripts/lib/no_code_comments_backends.py"),
            os.path.join(chk.REPO, "scripts/tests/test_no_code_comments.py"),
            os.path.join(chk.REPO, ".github/workflows/tests.yaml"),
        ]
        for f in files:
            self.assertTrue(os.path.isfile(f), f)
        s = self.scan(*files)
        self.assertEqual([], [(v["path"], v["text"]) for v in s["violations"]])


